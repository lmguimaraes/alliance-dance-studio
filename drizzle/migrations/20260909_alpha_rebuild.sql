CREATE OR REPLACE VIEW public.alpha_studio_catalog AS
SELECT
  s.id,
  s.name,
  s.description,
  s.capacity,
  s.size,
  s."hourlyRate" AS hourly_rate_cents,
  s."groupHourlyRate" AS group_hourly_rate_cents,
  COALESCE(NULLIF(s."imageUrl", ''), NULLIF(s.image, '')) AS image_url,
  s."isActive" AS is_active
FROM public.studios s;

CREATE OR REPLACE VIEW public.alpha_studio_schedule AS
WITH parsed AS (
  SELECT
    t.id,
    t."studioId" AS studio_id,
    t."dayOfWeek" AS day_of_week,
    t."startTime" AS start_time,
    t."endTime" AS end_time,
    (split_part(t."startTime", ':', 1)::integer * 60
      + split_part(t."startTime", ':', 2)::integer) AS start_minute,
    CASE WHEN t."endTime" = '24:00' THEN 1440 ELSE
      (split_part(t."endTime", ':', 1)::integer * 60
        + split_part(t."endTime", ':', 2)::integer)
    END AS end_minute
  FROM public."timeSlots" t
  WHERE t."isAvailable" IS TRUE
    AND t."dayOfWeek" BETWEEN 0 AND 6
    AND t."startTime" ~ '^(?:[01][0-9]|2[0-3]):[0-5][0-9]$'
    AND t."endTime" ~ '^(?:(?:[01][0-9]|2[0-3]):[0-5][0-9]|24:00)$'
)
SELECT * FROM parsed WHERE start_minute < end_minute;

COMMENT ON VIEW public.alpha_studio_catalog IS
  'Stable public studio catalog projection; contains no customer data.';
COMMENT ON VIEW public.alpha_studio_schedule IS
  'Validated public schedule projection over legacy public."timeSlots".';
