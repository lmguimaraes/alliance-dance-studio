-- Alliance Dance Studio alpha schema normalization
-- Additive and idempotent. It preserves existing data and canonicalizes legacy
-- PostgreSQL identifiers to the names used by the application.

SELECT pg_advisory_xact_lock(hashtext('alliance-dance-studio-alpha-schema-v2'));

CREATE EXTENSION IF NOT EXISTS pgcrypto;

DO $alpha$
DECLARE
  legacy_name text;
BEGIN
  IF to_regclass('public.studios') IS NULL THEN
    RAISE EXCEPTION 'Required relation public.studios is missing';
  END IF;

  IF to_regclass('public."timeSlots"') IS NULL THEN
    SELECT c.relname
      INTO legacy_name
      FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = 'public'
       AND c.relkind IN ('r', 'p')
       AND lower(c.relname) IN ('timeslots', 'time_slots')
     ORDER BY CASE c.relname WHEN 'timeslots' THEN 0 ELSE 1 END
     LIMIT 1;

    IF legacy_name IS NOT NULL THEN
      EXECUTE format('ALTER TABLE public.%I RENAME TO "timeSlots"', legacy_name);
    ELSE
      CREATE TABLE public."timeSlots" (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        "studioId" integer NOT NULL,
        "dayOfWeek" integer NOT NULL,
        "startTime" varchar NOT NULL,
        "endTime" varchar NOT NULL,
        "isAvailable" boolean NOT NULL DEFAULT true,
        "createdAt" timestamp without time zone NOT NULL DEFAULT now(),
        "updatedAt" timestamp without time zone NOT NULL DEFAULT now()
      );
    END IF;
  END IF;
END
$alpha$;

CREATE OR REPLACE FUNCTION pg_temp.alpha_rename_column(
  p_schema text,
  p_table text,
  p_old text,
  p_new text
) RETURNS void
LANGUAGE plpgsql
AS $alpha$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
     WHERE table_schema = p_schema AND table_name = p_table AND column_name = p_old
  ) AND NOT EXISTS (
    SELECT 1 FROM information_schema.columns
     WHERE table_schema = p_schema AND table_name = p_table AND column_name = p_new
  ) THEN
    EXECUTE format('ALTER TABLE %I.%I RENAME COLUMN %I TO %I', p_schema, p_table, p_old, p_new);
  END IF;
END
$alpha$;

