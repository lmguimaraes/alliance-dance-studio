-- Keep interval ranges synchronized even on databases where time_range was created
-- as a normal column rather than a generated column.
CREATE OR REPLACE FUNCTION public.alpha_sync_booking_time_range()
RETURNS trigger
LANGUAGE plpgsql
AS $alpha$
BEGIN
  NEW.time_range := tstzrange(NEW.start_at, NEW.end_at, '[)');
  NEW.updated_at := now();
  RETURN NEW;
END
$alpha$;

DO $alpha$
BEGIN
  IF to_regclass('public.studio_booking_items') IS NOT NULL
     AND EXISTS (
       SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'studio_booking_items' AND column_name = 'time_range'
          AND is_generated = 'NEVER'
     ) THEN
    DROP TRIGGER IF EXISTS alpha_sync_booking_time_range ON public.studio_booking_items;
    CREATE TRIGGER alpha_sync_booking_time_range
      BEFORE INSERT OR UPDATE OF start_at, end_at
      ON public.studio_booking_items
      FOR EACH ROW EXECUTE FUNCTION public.alpha_sync_booking_time_range();
    UPDATE public.studio_booking_items
       SET time_range = tstzrange(start_at, end_at, '[)')
     WHERE time_range IS DISTINCT FROM tstzrange(start_at, end_at, '[)');
  END IF;
END
$alpha$;

