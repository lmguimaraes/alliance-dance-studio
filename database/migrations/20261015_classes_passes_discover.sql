-- ---------------------------------------------------------------------------
-- Row level security
--
-- The application connects as the table owner, which bypasses RLS. Enabling
-- RLS without policies closes Supabase's public REST API (anon and
-- authenticated keys) for tables that hold customer data or admin content.
-- Only tables owned by the migrating role are changed, so the application's
-- own access is never affected.
-- ---------------------------------------------------------------------------
DO $rls$
DECLARE
  table_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'classes', 'class_passes', 'discover_entries',
    'bookings', 'reservations', 'users', 'studios', 'timeSlots',
    'studio_booking_groups', 'studio_booking_items', '_appMigrations'
  ] LOOP
    IF EXISTS (
      SELECT 1
        FROM pg_tables
       WHERE schemaname = 'public'
         AND tablename = table_name
         AND tableowner = current_user
    ) THEN
      EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
    END IF;
  END LOOP;
END
$rls$;
