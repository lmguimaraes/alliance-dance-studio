-- ---------------------------------------------------------------------------
-- Weekly classes (managed in /admin → Classes)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.classes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  style text NOT NULL,
  level text NOT NULL DEFAULT 'open',
  instructor_name text,
  instructor_instagram text,
  instructor_image_url text,
  studio_id integer REFERENCES public.studios(id) ON DELETE SET NULL,
  day_of_week smallint NOT NULL,
  start_time time without time zone NOT NULL,
  duration_minutes integer NOT NULL DEFAULT 60,
  starts_on date,
  ends_on date,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT classes_title_length CHECK (char_length(btrim(title)) BETWEEN 1 AND 120),
  CONSTRAINT classes_style_length CHECK (char_length(btrim(style)) BETWEEN 1 AND 60),
  CONSTRAINT classes_level_valid CHECK (level IN ('beginner', 'intermediate', 'advanced', 'open')),
  CONSTRAINT classes_day_valid CHECK (day_of_week BETWEEN 0 AND 6),
  CONSTRAINT classes_duration_valid CHECK (duration_minutes BETWEEN 15 AND 480),
  CONSTRAINT classes_ends_same_day CHECK (
    EXTRACT(EPOCH FROM start_time) / 60 + duration_minutes <= 1440
  ),
  CONSTRAINT classes_date_range_valid CHECK (
    starts_on IS NULL OR ends_on IS NULL OR ends_on >= starts_on
  ),
  CONSTRAINT classes_instagram_valid CHECK (
    instructor_instagram IS NULL OR instructor_instagram ~ '^[A-Za-z0-9._]{1,30}$'
  ),
  CONSTRAINT classes_image_url_valid CHECK (
    instructor_image_url IS NULL OR instructor_image_url ~ '^(https://|/)'
  )
);

CREATE INDEX IF NOT EXISTS classes_schedule_idx
  ON public.classes (day_of_week, start_time)
  WHERE is_active;
CREATE INDEX IF NOT EXISTS classes_studio_day_idx
  ON public.classes (studio_id, day_of_week)
  WHERE is_active AND studio_id IS NOT NULL;

COMMENT ON TABLE public.classes IS
  'Weekly recurring classes shown on /classes. A class assigned to a studio blocks that studio for rentals.';

-- ---------------------------------------------------------------------------
-- Class passes sold through Stripe Payment Links (managed in /admin → Passes)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.class_passes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category text NOT NULL DEFAULT 'classes',
  name_en text NOT NULL,
  name_fr text,
  name_es text,
  details_en text,
  details_fr text,
  details_es text,
  price_cents integer NOT NULL,
  currency text NOT NULL DEFAULT 'cad',
  stripe_url text NOT NULL,
  sort_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT class_passes_category_valid CHECK (category IN ('classes', 'rehearsal')),
  CONSTRAINT class_passes_name_length CHECK (char_length(btrim(name_en)) BETWEEN 1 AND 80),
  CONSTRAINT class_passes_price_valid CHECK (price_cents >= 0),
  CONSTRAINT class_passes_currency_valid CHECK (currency ~ '^[a-z]{3}$'),
  CONSTRAINT class_passes_stripe_url_valid CHECK (
    stripe_url ~ '^https://(buy|checkout)\.stripe\.com/'
  )
);

CREATE INDEX IF NOT EXISTS class_passes_display_idx
  ON public.class_passes (category, sort_order, id)
  WHERE is_active;

-- ---------------------------------------------------------------------------
-- Discover content: directors, dancers, teams and awards (managed in /admin)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.discover_entries (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section text NOT NULL,
  name text NOT NULL,
  subtitle_en text,
  subtitle_fr text,
  subtitle_es text,
  body_en text,
  body_fr text,
  body_es text,
  image_url text,
  link_url text,
  year integer,
  sort_order integer NOT NULL DEFAULT 0,
  is_published boolean NOT NULL DEFAULT true,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT discover_entries_section_valid CHECK (
    section IN ('directors', 'dancers', 'teams', 'awards')
  ),
  CONSTRAINT discover_entries_name_length CHECK (char_length(btrim(name)) BETWEEN 1 AND 160),
  CONSTRAINT discover_entries_image_url_valid CHECK (
    image_url IS NULL OR image_url ~ '^(https://|/)'
  ),
  CONSTRAINT discover_entries_link_url_valid CHECK (
    link_url IS NULL OR link_url ~ '^https://'
  ),
  CONSTRAINT discover_entries_year_valid CHECK (year IS NULL OR year BETWEEN 1900 AND 2100)
);

CREATE INDEX IF NOT EXISTS discover_entries_section_idx
  ON public.discover_entries (section, sort_order, id)
  WHERE is_published;

-- Admin listings filter bookings by date.
CREATE INDEX IF NOT EXISTS bookings_date_idx
  ON public.bookings ("bookingDate");

